type Props = {
  name: IconName;
  /** Points square. The glyphs are drawn on a 16-unit grid and scale to it. */
  size: number;
  /** Takes the colour of whatever it sits beside, which emoji could not. */
  color: string;
};

function Icon({ name, size, color }: Props) {
  const glyph = GLYPHS[name];
  return (
    <Svg width={size} height={size} viewBox="0 0 16 16">
      {glyph.paths.map((d, index) => (
        <Path
          key={index}
          d={d}
          fill={color}
          fillRule={glyph.evenOdd ? 'evenodd' : 'nonzero'}
        />
      ))}
    </Svg>
  );
}

export default Icon;
